import { AppLanguage, Emotion } from './types/amadeus';

export function normalizeAppLang(lang?: string): AppLanguage {
  const l = (lang || 'pt').toLowerCase().trim();
  if (l.startsWith('en')) return 'en';
  if (l.startsWith('ja') || l.startsWith('jp')) return 'ja';
  return 'pt';
}

export function getBcp47Lang(lang?: string): 'pt-BR' | 'en-US' | 'ja-JP' {
  const code = normalizeAppLang(lang);
  if (code === 'en') return 'en-US';
  if (code === 'ja') return 'ja-JP';
  return 'pt-BR';
}

